"""Generate the reference sections of the wiki in docs/ from the files they describe.

    .venv/bin/python tools/docs.py           # rewrite every generated section (make docs)
    .venv/bin/python tools/docs.py --check   # exit 1 naming each page that is out of date

Each generated section sits between two marker lines in a page that is otherwise written by hand,
so context goes above and below it and survives every run:

    docs/reference/make-targets.md   BEGIN_GENERATED: make-targets   the Makefile's `## ` comments
    docs/reference/settings.md       BEGIN_GENERATED: settings       local.yml.example and vault.yml.example,
                                                                     with defaults and wiring from
                                                                     defaults.yml and the roles' defaults
    docs/reference/roles/<role>.md   BEGIN_ANSIBLE_DOCS              roles/<role>/meta/argument_specs.yml,
                                                                     rendered by aar-doc with
                                                                     tools/templates/role.md.j2

A role without a page gets one, holding only its title and the markers.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
GROUP_VARS = ROOT / "inventory" / "group_vars" / "all"
ROLE_TEMPLATE = ROOT / "tools" / "templates" / "role.md.j2"

# "# ---------------------------------------------------------------- setup ----"
BANNER = re.compile(r"^# -{3,} (.+?) -{3,}$")


def roles() -> list[str]:
    return sorted(p.parent.parent.name for p in (ROOT / "roles").glob("*/meta/argument_specs.yml"))


def inject(text: str, name: str, body: str) -> str:
    """Replace what lies between a page's BEGIN_GENERATED and END_GENERATED markers for name."""
    begin, end = f"<!-- BEGIN_GENERATED: {name} -->", f"<!-- END_GENERATED: {name} -->"
    if text.count(begin) != 1 or text.count(end) != 1:
        raise SystemExit(f"expected one {begin} and one {end} line")
    head, rest = text.split(begin + "\n", 1)
    _, tail = rest.split(end + "\n", 1)
    note = "<!-- Generated by `make docs`: edit the source it names, not this section. -->\n"
    return f"{head}{begin}\n{note}\n{body.strip()}\n\n{end}\n{tail}"


def cell(text: str) -> str:
    return text.replace("|", "\\|").strip()


# ---------------------------------------------------------------- make targets ----


def make_targets() -> str:
    """One table per banner section of the Makefile, of every target with a `## ` description."""
    sections: list[tuple[str, list[tuple[str, str]]]] = []
    before: list[tuple[str, str]] = []  # `help`, above the first banner, goes in the first section
    for line in (ROOT / "Makefile").read_text().splitlines():
        banner = BANNER.match(line)
        if banner:
            sections.append((banner.group(1).strip().capitalize(), [] if sections else before))
            continue
        target = re.match(r"^([a-zA-Z0-9_-]+):(?!=)[^#]*## (.+)$", line)
        if target:
            (sections[-1][1] if sections else before).append((target.group(1), target.group(2)))
    out = []
    for title, targets in sections:
        if not targets:
            continue
        out += [f"### {title}", "", "| Target | What it does |", "|---|---|"]
        out += [f"| `make {name}` | {cell(text)} |" for name, text in targets]
        out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- settings ----


def _defaults() -> tuple[dict, dict[str, list[str]]]:
    """Every default a setting can have, and which role variables each setting feeds.

    The wiring is a role variable whose whole value is one setting, as in defaults.yml
    (`claude_code_remote_control: "{{ claude_remote_control }}"`) or a role's defaults
    (`proxmox_vm_cores: "{{ vm_cores | default(2) }}"`, which is where vm_cores' default lives).
    """
    wire = re.compile(r"""^(\w+): "\{\{ (\w+)(?: \| default\((.*)\))? \}\}"$""")
    defaults: dict = {}
    feeds: dict[str, list[str]] = {}
    files = sorted((ROOT / "roles").glob("*/defaults/main.yml")) + [GROUP_VARS / "defaults.yml"]
    for path in files:
        defaults.update(yaml.safe_load(path.read_text()) or {})
        for line in path.read_text().splitlines():
            m = wire.match(line)
            if m:
                feeds.setdefault(m.group(2), []).append(m.group(1))
                if m.group(3) is not None:
                    # default(value) or default(value, true): the first argument, as YAML reads it.
                    args = yaml.safe_load("[" + m.group(3).replace("'", '"') + "]")
                    defaults.setdefault(m.group(2), args[0])
    return defaults, feeds


def _value(value) -> str:
    if value == "":
        return '`""`'
    if isinstance(value, str) and "{{" in value:
        return "computed"
    dumped = yaml.safe_dump(value, default_flow_style=True, width=1000).strip()
    return f"`{cell(dumped.removesuffix('...').strip())}`"


def _role_of(variable: str) -> str | None:
    owners = [r for r in roles() if variable.startswith(r + "_")]
    return max(owners, key=len) if owners else None


def _parse_example(path: Path) -> list[tuple[str, list[tuple[list[str], list[tuple[str, object]]]]]]:
    """Sections of groups: the prose comment above some settings, and those settings with the value
    the example gives each (commented out in local.yml.example, set in vault.yml.example)."""
    setting = re.compile(r"^(?:# )?([a-z][a-z0-9_]*):(?: .*)?$")
    lines = path.read_text().splitlines()
    # The file's own header - the first comment block - says how to use the file, not a setting.
    start = next(i for i, line in enumerate(lines) if line.strip() == "" and i > 1)
    sections: list = [("", [])]
    prose: list[str] = []
    found: list[tuple[str, list[str]]] = []  # each setting with its lines of YAML

    def flush():
        nonlocal prose, found
        if found:
            parsed = [(name, yaml.safe_load("\n".join(text))[name]) for name, text in found]
            sections[-1][1].append((prose, parsed))
        prose, found = [], []

    for line in lines[start:]:
        banner = BANNER.match(line)
        uncommented = line[2:] if line.startswith("# ") else line
        if banner:
            flush()
            sections.append((banner.group(1).strip(), []))
        elif not line.strip():
            flush()
        elif setting.match(line):
            found.append((setting.match(line).group(1), [uncommented]))
        elif re.match(r"^#\s{3,}\S", line) and found:
            found[-1][1].append(uncommented)  # an indented continuation of the setting above
        elif line.startswith("#"):
            if found:
                flush()
            prose.append(line[1:].strip())
    flush()
    return [s for s in sections if s[1]]


def _prose(lines: list[str]) -> str:
    """A comment block as one paragraph, its docs/ paths linked from docs/reference/."""
    return re.sub(r"\bdocs/([\w./-]+\.md)", r"[docs/\1](../\1)", " ".join(lines))


def _sets(name: str, feeds: dict[str, list[str]]) -> list[str]:
    notes = []
    for var in feeds.get(name, []):
        role = _role_of(var)
        notes.append(f"sets `{var}`" + (f" ([`{role}`](roles/{role}.md))" if role else ""))
    if not feeds.get(name) and _role_of(name):
        notes.append(f"a variable of [`{_role_of(name)}`](roles/{_role_of(name)}.md)")
    return notes


def settings() -> str:
    defaults, feeds = _defaults()
    out = []
    for title, groups in _parse_example(GROUP_VARS / "local.yml.example"):
        out += [f"### {title}", ""] if title else []
        for prose, found in groups:
            out += [_prose(prose), ""] if prose else []
            out += ["| Setting | Default | Notes |", "|---|---|---|"]
            for name, example in found:
                if name not in defaults:
                    # A comment line read as a setting, or a typo: either way the page would lie.
                    raise SystemExit(f"local.yml.example sets {name}, which has no default anywhere")
                notes = []
                if example not in ("", [], {}, None) and example != defaults[name]:
                    notes.append(f"for example {_value(example)}")
                notes += _sets(name, feeds)
                out.append(f"| `{name}` | {_value(defaults[name])} | {'; '.join(notes)} |")
            out.append("")
    for title, groups in _parse_example(GROUP_VARS / "vault.yml.example"):
        out += [f"### Secrets: {title}" if title else "### Secrets", ""]
        for prose, found in groups:
            out += [_prose(prose), ""] if prose else []
            out += ["| Secret, in `vault.yml` | Notes |", "|---|---|"]
            out += [f"| `{name}` | {'; '.join(_sets(name, feeds))} |" for name, _ in found]
            out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- roles ----


def role_page(role: str, text: str) -> str:
    """The page with its BEGIN_ANSIBLE_DOCS section rendered by aar-doc from the role's argument_specs."""
    aar_doc = Path(sys.executable).parent / "aar-doc"
    if not aar_doc.exists():
        raise SystemExit(f"{aar_doc} is missing: run make venv")
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / f"{role}.md"
        page.write_text(text)
        subprocess.run(
            [
                str(aar_doc),
                "--output-file",
                str(page),
                "--output-template",
                str(ROLE_TEMPLATE),
                "--output-mode",
                "inject",
                str(ROOT / "roles" / role),
                "markdown",
            ],
            check=True,
            cwd=ROOT,
            stdout=subprocess.DEVNULL,
        )
        return re.sub(r"\n{3,}", "\n\n", page.read_text())


# ---------------------------------------------------------------- main ----


def expected() -> dict[Path, str]:
    """Every generated page, as the sources say it should read now."""
    pages: dict[Path, str] = {}
    targets = DOCS / "reference" / "make-targets.md"
    pages[targets] = inject(targets.read_text(), "make-targets", make_targets())
    settings_page = DOCS / "reference" / "settings.md"
    pages[settings_page] = inject(settings_page.read_text(), "settings", settings())
    for role in roles():
        page = DOCS / "reference" / "roles" / f"{role}.md"
        text = (
            page.read_text()
            if page.exists()
            else f"# `{role}`\n\n<!-- BEGIN_ANSIBLE_DOCS -->\n<!-- END_ANSIBLE_DOCS -->\n"
        )
        pages[page] = role_page(role, text)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated section is out of date")
    args = parser.parse_args()
    stale = []
    for path, text in expected().items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(text)
    if args.check and stale:
        names = ", ".join(str(p) for p in stale)
        print(f"Out of date: {names}. Run make docs and commit the result.", file=sys.stderr)
        return 1
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
