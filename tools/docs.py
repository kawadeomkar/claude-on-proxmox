"""Generate the reference sections of the wiki in docs/ from the files they describe.

    python tools/docs.py           # rewrite every generated section (just docs), with the project's Python
    python tools/docs.py --check   # exit 1 naming each page that is out of date

Each generated section sits between two marker lines in a page that is otherwise written by hand,
so context goes above and below it and survives every run:

    docs/reference/commands.md       BEGIN_GENERATED: commands       the justfile's recipes, by `just --json`
    docs/reference/settings.md       BEGIN_GENERATED: settings       local.yml.example and vault.yml.example,
                                                                     with defaults and wiring from
                                                                     defaults.yml and the roles' defaults,
                                                                     and each role variable's description
    docs/reference/roles/<role>.md   BEGIN_GENERATED: role           roles/<role>/: the variables from
                                                                     meta/argument_specs.yml, the internal
                                                                     values from vars/main.yml, and every
                                                                     task, with a flowchart of each task
                                                                     file, rendered by docsible with
                                                                     tools/templates/role.md.j2

A role without a page gets one, holding only its title and the markers. Text taken from a source is
escaped outside code spans, so a placeholder such as <name> reads as text on GitHub and on the site
rather than as an HTML tag that vanishes.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
GROUP_VARS = ROOT / "inventory" / "group_vars" / "all"
ROLE_TEMPLATE = ROOT / "tools" / "templates" / "role.md.j2"

# "# ---------------------------------------------------------------- setup ----"
BANNER = re.compile(r"^# -{3,} (.+?) -{3,}$")
# Spans left as they are: Markdown code, an HTML code element, a Markdown link's target.
CODE = re.compile(r"(`+)(?:.+?)\1|<code>.*?</code>|\]\([^)]*\)")
# What the role template writes where argument_specs gives no default; filled from defaults/main.yml.
NO_DEFAULT = "@@no-default@@"
# Where the role template puts the role's internal values, which docsible cannot show in full.
INTERNALS = "@@internals@@"
# What the role template writes for each level a task sits inside a block: an em space, put in after the
# escaping, which turned the template's own `&emsp;` into text.
INDENT = "@@indent@@"
# How a recipe's options and words sit under it in the commands table: an em space in.
INDENT_CELL = "&emsp;"


def roles() -> list[str]:
    return sorted(p.parent.parent.name for p in (ROOT / "roles").glob("*/meta/argument_specs.yml"))


def escape(text: str) -> str:
    """HTML-escape text outside code spans, so `<name>` stays text in both renderers."""
    out, last = [], 0
    for m in CODE.finditer(text):
        out += [html.escape(text[last : m.start()], quote=False), m.group(0)]
        last = m.end()
    return "".join(out + [html.escape(text[last:], quote=False)])


def cell(text: str) -> str:
    return escape(text).replace("|", "\\|").strip()


def inject(page: Path, text: str, name: str, body: str, source: str) -> str:
    """Replace what lies between the page's BEGIN_GENERATED and END_GENERATED markers for name."""
    begin, end = f"<!-- BEGIN_GENERATED: {name} -->", f"<!-- END_GENERATED: {name} -->"
    lines = text.splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == begin]
    ends = [i for i, line in enumerate(lines) if line.strip() == end]
    if len(starts) != 1 or len(ends) != 1 or starts[0] > ends[0]:
        raise SystemExit(f"{page.relative_to(ROOT)}: expected one {begin} line, then one {end} line")
    note = f"<!-- Generated by `just docs` from {source}: edit that, not this section. -->"
    section = [begin, note, "", body.strip(), "", end]
    return "\n".join(lines[: starts[0]] + section + lines[ends[0] + 1 :]) + "\n"


# ---------------------------------------------------------------- commands ----


def _just(*args: str) -> str:
    """just, as `just docs` gave it (JUST), or the one on PATH, on this checkout's justfile."""
    just = os.environ.get("JUST") or shutil.which("just")
    if not just:
        raise SystemExit("tools/docs.py: no just on PATH, which the commands page is read from")
    return subprocess.run(
        [just, "--justfile", str(ROOT / "justfile"), *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout


def _attribute(recipe: dict, name: str):
    return next(
        (attribute[name] for attribute in recipe["attributes"] if isinstance(attribute, dict) and name in attribute),
        None,
    )


def _usage(name: str, recipe: dict) -> str:
    """`just deploy [<name>...]`: the recipe and the words it takes, its options in the rows below it."""
    words = []
    for parameter in recipe["parameters"]:
        if parameter["long"] or parameter["short"] or parameter["name"] == "EXTRA":
            continue
        word = (
            parameter["name"].lower().removesuffix("s")
            if parameter["kind"] != "singular"
            else parameter["name"].lower()
        )
        # code opens one VM: the one name it needs is not optional.
        if name == "code" and word == "name":
            words.append("<name>")
        elif parameter["kind"] == "singular":
            words.append(f"[<{word}>]" if parameter["default"] is not None else f"<{word}>")
        elif not parameter["name"].endswith("S"):
            # A * parameter named in the singular takes one word, and its recipe refuses a second.
            words.append(f"[<{word}>]")
        else:
            words.append(f"[<{word}>...]" if parameter["kind"] == "star" else f"<{word}>...")
    return " ".join(["just", name, *words])


def _option(parameter: dict) -> str:
    """`-t, --tags ROLES`, or `--check` for a flag."""
    spelled = ", ".join([*([f"-{parameter['short']}"] if parameter["short"] else []), f"--{parameter['long']}"])
    return spelled if parameter["value"] is not None else f"{spelled} {parameter['name']}"


def commands() -> str:
    """One table per group of the justfile: every public recipe but help, its usage and [doc], and a row for each of
    its options and the words it takes, with each one's help. Only these fields of `just --json` are read, and the
    layout is this script's own, so a newer just generates the same page."""
    justfile = json.loads(_just("--json"))
    recipes = justfile["recipes"]
    # An alias is listed under its recipe: the name a recipe had before (just list for just status).
    aliases: dict[str, list[str]] = {}
    for alias in sorted(justfile.get("aliases") or {}):
        aliases.setdefault(justfile["aliases"][alias]["target"], []).append(alias)
    groups: dict[str, list[str]] = {}
    for name in _just("--summary", "--unsorted").split():
        recipe = recipes[name]
        if recipe["private"] or name == "help":
            continue
        groups.setdefault(_attribute(recipe, "group") or "other", []).append(name)
    out = []
    for group, names in groups.items():
        out += [f"### {group.capitalize()}", "", "| Recipe | What it does |", "|---|---|"]
        for name in names:
            recipe = recipes[name]
            out.append(f"| `{_usage(name, recipe)}` | {cell(_attribute(recipe, 'doc') or recipe['doc'] or '')} |")
            for parameter in recipe["parameters"]:
                if parameter["name"] == "EXTRA":
                    continue
                if parameter["long"]:
                    spelled = _option(parameter)
                else:
                    word = (
                        parameter["name"].lower().removesuffix("s")
                        if parameter["kind"] != "singular"
                        else parameter["name"].lower()
                    )
                    spelled = f"<{word}>"
                out.append(f"| {INDENT_CELL}`{spelled}` | {cell(parameter['help'] or '')} |")
            for alias in aliases.get(name, []):
                out.append(
                    f"| {INDENT_CELL}`just {alias}` | Another name for `just {name}`, and the same in every way |"
                )
        out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- settings ----


def specs() -> dict[str, dict[str, dict]]:
    """Every role variable's argument_specs entry, by role: the main entry point's wins."""
    out: dict[str, dict[str, dict]] = {}
    for role in roles():
        entry_points = yaml.safe_load((ROOT / "roles" / role / "meta" / "argument_specs.yml").read_text())
        merged: dict[str, dict] = {}
        for _name, spec in sorted(entry_points["argument_specs"].items(), key=lambda kv: kv[0] != "main"):
            for var, details in (spec.get("options") or {}).items():
                merged.setdefault(var, details or {})
        out[role] = merged
    return out


def wiring() -> tuple[dict, dict[str, list[str]]]:
    """Every default a setting can have, and which variables each setting sets directly.

    The wiring is a variable whose whole value is one setting, as in defaults.yml
    (`claude_code_login_desktop: "{{ login_desktop }}"`) or a role's defaults
    (`proxmox_vm_cores: "{{ vm_cores | default(2) }}"`, which is where vm_cores' default lives).
    Role defaults load first and defaults.yml after, as Ansible ranks them.
    """
    wire = re.compile(r"""^(\w+): "\{\{ (\w+)(?: \| default\((.*)\))? \}\}"$""")
    defaults: dict = {}
    feeds: dict[str, list[str]] = {}
    files = sorted((ROOT / "roles").glob("*/defaults/main.yml")) + [GROUP_VARS / "defaults.yml"]
    for path in files:
        defaults.update(yaml.safe_load(path.read_text()) or {})
        for line in path.read_text().splitlines():
            m = wire.match(line)
            if m:
                feeds.setdefault(m.group(2), []).append(m.group(1))
                if m.group(3) is not None:
                    # default(value) or default(value, true): the first argument, as YAML reads it - or,
                    # a bare name, the variable it names, as Ansible reads it
                    # (`proxmox_vm_memory_min_mb: "{{ vm_memory_min_mb | default(proxmox_vm_memory_mb) }}"`).
                    first = m.group(3).split(",")[0].strip()
                    if re.fullmatch(r"[a-z_]\w*", first) and first not in ("true", "false", "none", "omit"):
                        defaults.setdefault(m.group(2), "{{ " + first + " }}")
                    else:
                        args = yaml.safe_load("[" + m.group(3).replace("'", '"') + "]")
                        defaults.setdefault(m.group(2), args[0])
    return defaults, feeds


def role_of(variable: str, role_specs: dict[str, dict[str, dict]]) -> str | None:
    """The role whose argument_specs list the variable, or None for a variable no role takes."""
    return next((role for role, options in role_specs.items() if variable in options), None)


def set_by(name: str, feeds: dict[str, list[str]], role_specs: dict) -> list[str]:
    """The role variables a setting ends up in, following settings that set other settings."""
    out, todo, seen = [], list(feeds.get(name, [])), set()
    while todo:
        var = todo.pop(0)
        if var in seen:
            continue
        seen.add(var)
        if role_of(var, role_specs):
            out.append(var)
        todo += feeds.get(var, [])
    return out


def first_sentence(description) -> str:
    text = " ".join(description) if isinstance(description, list) else str(description or "")
    m = re.match(r"(.+?\.)(?:\s|$)", text.strip())
    return (m.group(1) if m else text).strip()


def value(v) -> str:
    """A default as the table shows it: YAML in a code span, or what a template value stands for."""
    if v == "":
        return '`""`'
    if isinstance(v, str) and "{{" in v:
        same = re.fullmatch(r"\{\{ (\w+) \}\}", v)
        return f"same as `{same.group(1)}`" if same else "computed"
    dumped = yaml.safe_dump(v, default_flow_style=True, width=1000).strip().removesuffix("...").strip()
    if "|" in dumped:
        # A pipe splits a GitHub table cell, and `\|` inside backticks shows its backslash on the site.
        return f"<code>{html.escape(dumped, quote=False).replace('|', '&#124;')}</code>"
    return f"`{dumped}`"


def parse_example(path: Path, secret: bool) -> list[tuple[str, list[tuple[list[str], list[tuple[str, object]]]]]]:
    """Sections of groups: the prose comment above some settings, and those settings with the value
    the example gives each. Settings in local.yml.example are commented out (`# name: value`); in
    vault.yml.example only uncommented lines are settings, so a comment that happens to start
    `# word: ...` stays prose."""
    lines = path.read_text().splitlines()
    rel = path.relative_to(ROOT)
    # Everything above the first banner is the file's own header: how to use it, not a setting.
    start = next((i for i, line in enumerate(lines) if BANNER.match(line)), None)
    if start is None:
        raise SystemExit(f"{rel}: no `# --- Section ---` banner, so nothing marks where the settings start")
    setting = re.compile(r"^([a-z][a-z0-9_]*):(?: .*)?$" if secret else r"^# ([a-z][a-z0-9_]*):(?: .*)?$")
    sections: list = []
    prose: list[str] = []
    found: list[tuple[str, list[str]]] = []  # each setting with its lines of YAML

    def flush():
        nonlocal prose, found
        if found:
            parsed = [(name, yaml.safe_load("\n".join(text))[name]) for name, text in found]
            sections[-1][1].append((prose, parsed))
        prose, found = [], []

    for line in lines[start:]:
        banner = BANNER.match(line)
        uncommented = line[2:] if line.startswith("# ") else line
        if banner:
            flush()
            sections.append((banner.group(1).strip(), []))
        elif not line.strip():
            flush()
        elif setting.match(line):
            found.append((setting.match(line).group(1), [uncommented]))
        elif not secret and re.match(r"^#\s{3,}\S", line) and found:
            found[-1][1].append(uncommented)  # an indented continuation of the setting above
        elif line.startswith("#"):
            if found:
                flush()
            prose.append(line[1:].strip())
    flush()

    names = [name for _, groups in sections for _, found_ in groups for name, _ in found_]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise SystemExit(f"{rel} lists {', '.join(duplicates)} twice: a comment line read as a setting?")
    if secret:
        keys = sorted((yaml.safe_load(path.read_text()) or {}).keys())
        if sorted(names) != keys:
            raise SystemExit(f"{rel}: the settings read ({sorted(names)}) are not the file's keys ({keys})")
    return [s for s in sections if s[1]]


def _prose(lines: list[str]) -> str:
    """A comment block as one paragraph, escaped, its docs/ paths linked from docs/reference/."""
    return re.sub(r"\bdocs/([\w./-]+\.md)", r"[docs/\1](../\1)", escape(" ".join(lines)))


def _notes(name: str, feeds: dict[str, list[str]], role_specs: dict) -> list[str]:
    """What a setting does, from the description of the role variable it is or ends up in."""
    targets = [name] if role_of(name, role_specs) else set_by(name, feeds, role_specs)
    notes = []
    for var in targets:
        role = role_of(var, role_specs)
        sentence = first_sentence(role_specs[role][var].get("description"))
        where = f"[`{role}`](roles/{role}.md)"
        if var == name:
            notes.append(f"{escape(sentence)} A variable of {where}." if sentence else f"A variable of {where}.")
        else:
            notes.append(f"Sets `{var}` ({where}): {escape(sentence)}" if sentence else f"Sets `{var}` ({where}).")
    return notes


def settings() -> str:
    defaults, feeds = wiring()
    role_specs = specs()
    # The setting a role variable is set through, for a default that is one: vm_memory_mb, not
    # proxmox_vm_memory_mb, is what the reader of this page sets.
    fed_by = {var: setting for setting, variables in feeds.items() for var in variables}
    out = []
    for title, groups in parse_example(GROUP_VARS / "local.yml.example", secret=False):
        out += [f"### {title}", ""]
        for prose, found in groups:
            out += [_prose(prose), ""] if prose else []
            out += ["| Setting | Default | Notes |", "|---|---|---|"]
            for name, example in found:
                if name not in defaults:
                    # A comment line read as a setting, or a typo: either way the page would lie.
                    raise SystemExit(f"local.yml.example sets {name}, which has no default anywhere")
                default = defaults[name]
                computed = isinstance(default, str) and "{{" in default
                if not computed and example is not None and default is not None:
                    if not isinstance(example, type(default)) and not isinstance(default, type(example)):
                        raise SystemExit(
                            f"local.yml.example gives {name} a {type(example).__name__}, but its default is a "
                            f"{type(default).__name__}: a comment line read as a setting?"
                        )
                notes = _notes(name, feeds, role_specs)
                if example not in ("", [], {}, None) and example != default:
                    notes.append(f"For example {value(example)}.")
                shown = value(default)
                same = re.fullmatch(r"\{\{ (\w+) \}\}", default) if isinstance(default, str) else None
                if same and same.group(1) in fed_by:
                    shown = f"same as `{fed_by[same.group(1)]}`"
                out.append(f"| `{name}` | {shown} | {' '.join(notes)} |")
            out.append("")
    for title, groups in parse_example(GROUP_VARS / "vault.yml.example", secret=True):
        out += [f"### Secrets: {title}", ""]
        for prose, found in groups:
            out += [_prose(prose), ""] if prose else []
            out += ["| Secret, in `vault.yml` | Notes |", "|---|---|"]
            out += [f"| `{name}` | {' '.join(_notes(name, feeds, role_specs))} |" for name, _ in found]
            out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- roles ----


def internals(role: str) -> str:
    """The role's vars/main.yml as a table, every value as written: docsible's own reading of the file
    shows a multi-line value as a placeholder."""
    path = ROOT / "roles" / role / "vars" / "main.yml"
    values = (yaml.safe_load(path.read_text()) or {}) if path.exists() else {}
    if not values:
        return ""
    computed = sum(isinstance(v, str) and "{{" in v for v in values.values())
    rows = "\n".join(f"| `{name}` | {_literal(v)} |" for name, v in values.items())
    share = "All" if computed == len(values) else f"{computed} of the"
    said = f" {share} {len(values)} are computed during a run, from earlier tasks' results." if computed else ""
    return (
        f"## Internal values\n\nSet in `roles/{role}/vars/main.yml`. These are not settings: Ansible ranks a "
        f"role's vars above `local.yml`, so a value set there has no effect.{said}\n\n"
        f"| Name | Value |\n|---|---|\n{rows}"
    )


def _literal(v) -> str:
    """A value as written, on one line: a code span, or a code element where a span cannot hold it."""
    text = " ".join(v.split()) if isinstance(v, str) else json.dumps(v)
    if "|" in text or "`" in text or "</" in text:
        return "<code>" + text.replace("&", "&amp;").replace("<", "&lt;").replace("|", "&#124;") + "</code>"
    return f"`{text}`" if text else '`""`'


def _role_section(role: str, section: str) -> str:
    """docsible's output, finished: internal values put in, missing defaults filled, text escaped and
    blank lines collapsed - outside the flowcharts' fences, which pass through as they are."""
    defaults = yaml.safe_load((ROOT / "roles" / role / "defaults" / "main.yml").read_text()) or {}
    out: list[str] = []
    fence = False
    for line in section.replace(INTERNALS, internals(role)).splitlines():
        if line.startswith("```"):
            fence = not fence
        elif not fence:
            if NO_DEFAULT in line:
                var = re.match(r"\| `(\w+)` \|", line)
                shown = value(defaults[var.group(1)]) if var and var.group(1) in defaults else ""
                line = line.replace(NO_DEFAULT, shown)
            line = escape(line) if not line.startswith("|") else _escape_row(line)
            line = line.replace(INDENT, "&emsp;")
            if not line and (not out or not out[-1]):
                continue
        out.append(line)
    return "\n".join(out).strip()


def _escape_row(row: str) -> str:
    """Escape a table row's cells, keeping the `|` separators and escaped `\\|` inside cells."""
    cells = re.split(r"(?<!\\)\|", row)
    return "|".join(escape(c) if c.strip() not in ("---", "") else c for c in cells)


def role_page(role: str, page: Path, text: str) -> str:
    """The page with its role section rendered by docsible from roles/<role>/."""
    docsible = Path(sys.executable).parent / "docsible"
    if not docsible.exists():
        raise SystemExit(f"{docsible} is missing: run just install")
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / f"{role}.md"
        command = [str(docsible), "--role", str(ROOT / "roles" / role), "--md-template", str(ROLE_TEMPLATE)]
        command += ["--graph", "--no-backup", "--no-docsible", "--output", str(work)]
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
        if result.returncode != 0 or not work.exists():
            said = (result.stdout + result.stderr).strip()
            raise SystemExit(f"{page.relative_to(ROOT)}: docsible failed on roles/{role}: {said}")
        rendered = work.read_text()
    # docsible wraps what it renders in markers of its own.
    section = rendered.split("<!-- DOCSIBLE START -->", 1)[-1].split("<!-- DOCSIBLE END -->", 1)[0]
    source = f"roles/{role}/meta/argument_specs.yml, vars/main.yml and tasks/"
    return inject(page, text, "role", _role_section(role, section), source)


# ---------------------------------------------------------------- main ----


def expected() -> dict[Path, str]:
    """Every generated page, as the sources say it should read now."""
    pages: dict[Path, str] = {}
    page = DOCS / "reference" / "commands.md"
    pages[page] = inject(
        page, page.read_text(), "commands", commands(), "the justfile's recipes, their `[doc]` and `[arg]` help"
    )
    page = DOCS / "reference" / "settings.md"
    source = "inventory/group_vars/all/local.yml.example and vault.yml.example, the defaults and argument_specs"
    pages[page] = inject(page, page.read_text(), "settings", settings(), source)
    for role in roles():
        page = DOCS / "reference" / "roles" / f"{role}.md"
        text = (
            page.read_text()
            if page.exists()
            else f"# `{role}`\n\n<!-- BEGIN_GENERATED: role -->\n<!-- END_GENERATED: role -->\n"
        )
        pages[page] = role_page(role, page, text)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated section is out of date")
    args = parser.parse_args()
    stale = []
    for path, text in expected().items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(text)
    if args.check and stale:
        names = ", ".join(str(p) for p in stale)
        print(f"Out of date: {names}. Run just docs and commit the result.", file=sys.stderr)
        return 1
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
